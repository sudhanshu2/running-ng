COMPANION_WAIT_START = 2.0
MONITOR_WAIT_START = 1.0


class SubprocessrExit(Enum):
    Normal = 1
    Error = 2
    Timeout = 3
    Dryrun = 4


B = TypeVar("B", bound="Benchmark")


class Benchmark:
    def __init__(
        self,
        suite_name: str,
        name: str,
        wrapper: str | None = None,
        timeout: int | None = None,
        override_cwd: Path | None = None,
        companion: str | None = None,
        runtime_specific_modifiers_strategy: (
            Callable[[Runtime], Sequence[Modifier]] | None
        ) = None,
        prepend: str | None = None,
        monitors: list[str] | None = None,
        execution_dump: str | None = None,
        delay_execution: float | None = None,
        skip_env: bool| None = False,
        postexecution: list[str] | None = None,
        **kwargs,
    ):
        self.name = name
        self.suite_name = suite_name
        self.env_args: dict[str, str]
        self.env_args = {}
        self.wrapper: list[str]
        if wrapper is not None:
            self.wrapper = split_quoted(wrapper)
        else:
            self.wrapper = []
        if companion is not None:
            self.companion = split_quoted(companion)
        else:
            self.companion = []
        if prepend is not None:
            self.prepend = prepend.split()
        else:
            self.prepend = list()
        self.monitors = list()
        if monitors is not None:
            for monitor in monitors:
                self.monitors.append(monitor.split())
        self.postexecution = list()
        if postexecution is not None:
            for post_cmd in postexecution:
              self.postexecution.append(post_cmd.split())
        if execution_dump is not None:
            self.execution_dump = execution_dump
        else:
            self.execution_dump = None
        if delay_execution is not None:
            self.delay_execution = delay_execution
        else:
            self.delay_execution = None
        self.timeout = timeout
        self.skip_env = skip_env
        # ignore the current working directory provided by
        # commands like runbms or minheap
        # certain benchmarks expect to be invoked from certain directories
        self.override_cwd = override_cwd
        self.runtime_specific_modifiers_strategy: Callable[
            [Runtime], Sequence[Modifier]
        ]
        if runtime_specific_modifiers_strategy is not None:
            self.runtime_specific_modifiers_strategy = (
                runtime_specific_modifiers_strategy
            )
        else:
            self.runtime_specific_modifiers_strategy = lambda _runtime: []

    def get_env_str(self) -> str:
        return " ".join(
            [
                f"{k}={smart_quote(os.path.expandvars(v))}"
                for (k, v) in self.env_args.items()
            ]
        )

    def get_full_args(self, runtime: Runtime) -> list[str | Path]:
        # makes a copy because the subclass might change the list
        # also for type variance (covariant list copy)
        return list(self.wrapper)

    def get_tokens(self) -> dict[str, str]:
        # tokens are special variables that are replaced by values
        # generated by runtime, benchmark execution or modifiers
        # tokens are expected to be of the form @{TOKEN}
        # by default, benchmarks don't have any tokens.
        return dict()

    def replace_tokens(
        self,
        cmd: list[str] | str | dict[str, str],
        invocation: int | None = None,
        heap_size: int | None = None,
        pid: int | None = None,
    ) -> str:
        # iterate over the command and replace all tokens
        # tokens are expected to be of the form @{TOKEN}
        if isinstance(cmd, dict):
            for k in cmd.keys():
                cmd[k] = self.replace_tokens(
                    cmd[k],
                    invocation=invocation,
                    heap_size=heap_size,
                    pid=pid,
                )
            return cmd
        if isinstance(cmd, list):
            for i in range(len(cmd)):
                cmd[i] = self.replace_tokens(
                    cmd[i],
                    invocation=invocation,
                    heap_size=heap_size,
                    pid=pid,
                )
            return cmd
        assert isinstance(cmd, str)
        tokens = self.get_tokens()
        if invocation is not None:
            tokens["INVOCATION"] = invocation
        if heap_size is not None:
            tokens["BMHEAP"] = heap_size
        if pid is not None:
            tokens["BMPID"] = pid
        potential_tokens = list(re.finditer(r"@[A-Z]+", cmd))
        if len(potential_tokens) == 0:
            return cmd
        cmd_without_tokens = ""
        curr_pos = 0
        for potential_token in potential_tokens:
            cmd_without_tokens += cmd[curr_pos:potential_token.span()[0]]
            tk = potential_token.group()[1:]
            if tk in tokens:
                if isinstance(tokens[tk], str):
                    cmd_without_tokens += tokens[tk]
                else:
                    cmd_without_tokens += str(tokens[tk])
            else:
                cmd_without_tokens += f"@{tk}"
            curr_pos = potential_token.span()[1]
        cmd_without_tokens += cmd[curr_pos:len(cmd)]
        return cmd_without_tokens

    def get_runtime_specific_modifiers(self, runtime: Runtime) -> Sequence[Modifier]:
        return self.runtime_specific_modifiers_strategy(runtime)

    def attach_modifiers(self: B, modifiers: Sequence[Modifier]) -> B:
        b = deepcopy(self)
        for m in modifiers:
            if not m.should_attach(self.suite_name, self.name):
                continue
            elif type(m) is Wrapper:
                b.wrapper.extend(m.val)
            elif type(m) is Companion:
                b.companion.extend(m.val)
            elif type(m) is EnvVar:
                b.env_args[m.var] = m.val
            elif type(m) is ModifierSet:
                logging.warning("ModifierSet should have been flattened")
        return b

    def to_string(self, runtime: Runtime, invocation: int | None = None, heap_size: int | None = None) -> str:
        cmd = "{} {} {}".format(
            " ".join(self.prepend),
            self.get_env_str(),
            " ".join(
                [
                    smart_quote(os.path.expandvars(x))
                    for x in self.get_full_args(runtime)
                ]
            ),
        )
        return self.replace_tokens(
            cmd, invocation=invocation, heap_size=heap_size
        )

    def run(
        self, runtime: Runtime, cwd: Path | None = None, invocation: int | None = None, heap_size: int | None = None
    ) -> tuple[bytes, bytes, SubprocessrExit]:
        from running import suite

        if suite.is_dry_run():
            print(self.to_string(runtime, invocation=invocation, heap_size=heap_size), file=sys.stderr)
            return b"", b"", SubprocessrExit.Dryrun
        else:
            if self.delay_execution is not None:
                sleep(self.delay_execution)
            cmd = self.get_full_args(runtime)
            cmd = [os.path.expandvars(x) for x in cmd]
            env_args = os.environ.copy()
            env_args_to_add = {
                k: os.path.expandvars(v) for k, v in self.env_args.items()
            }
            if self.skip_env is True:
              env_list = [f"{k}={os.path.expandvars(v)}" for (k, v) in env_args_to_add.items()]
              cmd = self.prepend + env_list + cmd
            else:
              cmd = self.prepend + cmd
              env_args.update(env_args_to_add)
              env_args = self.replace_tokens(env_args, invocation=invocation, heap_size=heap_size)
            cmd = self.replace_tokens(cmd, invocation=invocation, heap_size=heap_size)
            companion_out = b""
            stdout: bytes | None
            if self.companion:
                companion_p = subprocess.Popen(
                    self.companion, stdout=subprocess.PIPE, stderr=subprocess.STDOUT
                )
                sleep(COMPANION_WAIT_START)
            try:
                stdout_dump = subprocess.PIPE
                stderr_dump = subprocess.STDOUT
                execution_dump_file = None
                execution_start_time = None
                if self.execution_dump is not None:
                    self.execution_dump = self.replace_tokens(self.execution_dump, invocation=invocation, heap_size=heap_size)
                    execution_dump_file = open(self.execution_dump, "w")
                    stdout_dump = execution_dump_file
                    stderr_dump = execution_dump_file
                    curr_time = datetime.now().strftime("%Y.%m.%d_%H.%M.%S")
                    execution_dump_file.write(f"START TIME: {curr_time}\n")
                    execution_dump_file.flush()
                    execution_start_time = time()
                if self.monitors is not None:
                    p = subprocess.Popen(
                        cmd,
                        env=env_args,
                        stdout=stdout_dump,
                        stderr=stderr_dump,
                        cwd=self.override_cwd if self.override_cwd else cwd,
                    )
                    sleep(MONITOR_WAIT_START)
                    p_monitors = list()
                    for monitor in self.monitors:
                        copy_monitor = deepcopy(monitor)
                        copy_monitor = self.replace_tokens(copy_monitor, invocation=invocation, heap_size=heap_size, pid=p.pid)
                        p_monitors.append(
                            subprocess.Popen(
                                copy_monitor,
                                stdout=stdout_dump,
                                stderr=stderr_dump,
                                cwd=self.override_cwd if self.override_cwd else cwd,
                            )
                        )
                    stdout, _ = p.communicate(timeout=self.timeout,)
                    for i in range(len(p_monitors)):
                        _, _ = p_monitors[i].communicate()
                else:
                    p = subprocess.run(
                        cmd,
                        env=env_args,
                        stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT,
                        timeout=self.timeout,
                        cwd=self.override_cwd if self.override_cwd else cwd,
                    )
                    stdout = p.stdout
                subprocess_exit = SubprocessrExit.Normal if p.returncode == 0 else SubprocessrExit.Error
            except subprocess.CalledProcessError as e:
                subprocess_exit = SubprocessrExit.Error
                stdout = e.stdout
                if self.execution_dump is not None:
                    execution_dump_file.write(f"ERROR -> SUBPROCESS ERROR\n")
            except subprocess.TimeoutExpired as e:
                subprocess_exit = SubprocessrExit.Timeout
                stdout = e.stdout
                if self.execution_dump is not None:
                    execution_dump_file.write(f"ERROR -> SUBPROCESS TIMEOUT\n")
            except Exception as e:
                subprocess_exit = SubprocessrExit.Error
                stdout = b""
                if self.execution_dump is not None:
                    execution_dump_file.write(f"EXCEPTION -> {e}\n")
            finally:
                if execution_start_time is not None:
                    execution_end_time = time()
                for post_cmd in self.postexecution:
                  copy_post_cmd = deepcopy(post_cmd)
                  copy_post_cmd = self.replace_tokens(copy_post_cmd, invocation=invocation, heap_size=heap_size, pid=p.pid)
                  p = subprocess.run(
                        copy_post_cmd,
                        env=env_args,
                        stdout=stdout_dump,
                        stderr=stderr_dump,
                        cwd=self.override_cwd if self.override_cwd else cwd,
                    )
                if self.execution_dump is not None:
                    curr_time = datetime.now().strftime("%Y.%m.%d_%H.%M.%S")
                    execution_dump_file.flush()
                    if execution_start_time is not None and execution_end_time is not None:
                        total_execution_time = execution_end_time - execution_start_time
                        execution_dump_file.write(
                            f"EXECUTION TIME (seconds) -> {total_execution_time:.2f}\n"
                        )
                    execution_dump_file.write(f"END TIME: {curr_time}\n")
                    execution_dump_file.close()
                    execution_dump_file = open(self.execution_dump, "r")
                    stdout = execution_dump_file.read()
                    execution_dump_file.close()
                if self.companion:
                    try:
                        companion_stdout, _ = companion_p.communicate(timeout=10)
                        companion_out += companion_stdout
                    except subprocess.TimeoutExpired:
                        logging.warning(
                            "Companion program not exited after"
                            " 10 seconds timeout."
                            " Trying to kill ..."
                        )
                        try:
                            companion_p.kill()
                        except PermissionError:
                            logging.warning("Failed to kill.")
                        companion_stdout, _ = companion_p.communicate()
                        companion_out += companion_stdout

                if self.execution_dump is not None:
                    return stdout.encode("utf-8"), companion_out, subprocess_exit
            return stdout if stdout else b"", companion_out, subprocess_exit


class BinaryBenchmark(Benchmark):
    def __init__(self, program: Path, program_args: list[str | Path], **kwargs):
        super().__init__(**kwargs)
        self.program = program
        self.program_args = program_args
        assert program.exists()

    def __str__(self) -> str:
        return self.to_string(DummyRuntime(""))

    def attach_modifiers(self, modifiers: Sequence[Modifier]) -> "BinaryBenchmark":
        bb = super().attach_modifiers(modifiers)
        for m in modifiers:
            if not m.should_attach(self.suite_name, self.name):
                continue
            elif type(m) is ProgramArg:
                bb.program_args.extend(m.val)
            elif type(m) is JVMArg:
                logging.warning("JVMArg not respected by BinaryBenchmark")
            elif isinstance(m, JVMClasspathAppend) or type(m) is JVMClasspathPrepend:
                logging.warning("JVMClasspath not respected by BinaryBenchmark")
            elif type(m) is JSArg:
                logging.warning("JSArg not respected by BinaryBenchmark")
        return bb

    def get_full_args(self, runtime: Runtime) -> list[str | Path]:
        cmd = super().get_full_args(runtime)
        cmd.append(self.program)
        cmd.extend(self.program_args)
        return cmd


class JavaBenchmark(Benchmark):
    def __init__(
        self, jvm_args: list[str], program_args: list[str], cp: list[str], **kwargs
    ):
        super().__init__(**kwargs)
        self.jvm_args = jvm_args
        self.program_args = program_args
        self.cp = cp

    def get_classpath_args(self) -> list[str]:
        return ["-cp", ":".join(self.cp)] if self.cp else []

    def __str__(self) -> str:
        return self.to_string(DummyRuntime("java"))

    def attach_modifiers(self, modifiers: Sequence[Modifier]) -> "JavaBenchmark":
        jb = super().attach_modifiers(modifiers)
        for m in modifiers:
            if not m.should_attach(self.suite_name, self.name):
                continue
            if type(m) is JVMArg:
                jb.jvm_args.extend(m.val)
            elif type(m) is ProgramArg:
                jb.program_args.extend(m.val)
            elif isinstance(m, JVMClasspathAppend):
                jb.cp.extend(m.val)
            elif type(m) is JVMClasspathPrepend:
                jb.cp = m.val + jb.cp
            elif type(m) is JSArg:
                logging.warning("JSArg not respected by JavaBenchmark")
        return jb

    def get_full_args(self, runtime: Runtime) -> list[str | Path]:
        cmd = super().get_full_args(runtime)
        cmd.append(runtime.get_executable())
        cmd.extend(self.jvm_args)
        cmd.extend(self.get_classpath_args())
        cmd.extend(self.program_args)
        return cmd
    
    def get_tokens(self) -> dict[str, str]:
        return {
            "BMNAME": self.name,
        }


class JavaScriptBenchmark(Benchmark):
    def __init__(
        self, js_args: list[str], program: str, program_args: list[str], **kwargs
    ):
        super().__init__(**kwargs)
        self.js_args = js_args
        self.program = program
        self.program_args = program_args

    def __str__(self) -> str:
        return self.to_string(DummyRuntime("js"))

    def attach_modifiers(self, modifiers: Sequence[Modifier]) -> "JavaScriptBenchmark":
        jb = super().attach_modifiers(modifiers)
        for m in modifiers:
            if not m.should_attach(self.suite_name, self.name):
                continue
            if type(m) is ProgramArg:
                jb.program_args.extend(m.val)
            elif type(m) is JVMArg:
                logging.warning("JVMArg not respected by JavaScriptBenchmark")
            elif isinstance(m, JVMClasspathAppend) or type(m) is JVMClasspathPrepend:
                logging.warning("JVMClasspath not respected by JavaScriptBenchmark")
            elif type(m) is JSArg:
                jb.js_args.extend(m.val)
        return jb

    def get_full_args(self, runtime: Runtime) -> list[str | Path]:
        cmd = super().get_full_args(runtime)
        cmd.append(runtime.get_executable())
        cmd.extend(self.js_args)
        cmd.append(self.program)
        if isinstance(runtime, D8):
            cmd.append("--")
        elif isinstance(runtime, JavaScriptCore):
            cmd.append("--")
        elif isinstance(runtime, SpiderMonkey):
            pass
        else:
            raise TypeError(
                f"{runtime} is of type {type(runtime)},"
                " and not a valid runtime"
                " for JavaScriptBenchmark"
            )
        cmd.extend(self.program_args)
        return cmd


class JuliaBenchmark(Benchmark):
    def __init__(
        self,
        julia_args: list[str],
        suite_path: Path,
        program_args: list[str],
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.julia_args = julia_args
        self.suite_path = suite_path
        self.program_args = program_args

    def __str__(self) -> str:
        return self.to_string(DummyRuntime("julia"))

    def attach_modifiers(self, modifiers: Sequence[Modifier]) -> "JuliaBenchmark":
        jb = super().attach_modifiers(modifiers)
        for m in modifiers:
            if type(m) is JuliaArg:
                jb.julia_args.extend(m.val)
            elif type(m) is ProgramArg:
                jb.program_args.extend(m.val)
        return jb

    def get_full_args(self, runtime: Runtime) -> list[str | Path]:
        cmd = super().get_full_args(runtime)
        cmd.append(runtime.get_executable())
        cmd.extend(self.julia_args)
        cmd.append(f"--project={self.suite_path}")
        cmd.append(str(self.suite_path / "run_benchmarks.jl"))
        cmd.extend(self.name.split("/"))
        cmd.extend(["-n", "1"])  # one run
        cmd.extend(self.program_args)
        return cmd
